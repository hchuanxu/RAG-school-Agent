# 回答生成提示词
ANSWER_GENERATION_PROMPT = """请基于以下检索到的知识库内容，回答用户问题。

用户问题：
{question}

检索到的参考资料：
{context}

回答要求：
1. 答案必须严格基于上述参考资料，不得编造或引用资料外的信息。
2. 排版格式规范：
   - 根据内容语义，合理使用 **小标题**、分点列表（•）、编号列表（1. 2. 3.）等 Markdown 结构。
   - 涉及多个方面时，用 **小标题** 分段，每段聚焦一个要点。
   - 涉及步骤、流程时，使用编号列表（1. 2. 3.）。
   - 涉及并列要素时，使用无序列表（• 或 -）。
   - 段落之间留空行，保持层次清晰、排版美观。
3. 引用方式：在关键信息后标注来源编号，如 [来源1]、[来源2]，不在正文中插入完整文件名。
4. 若参考资料不足以完整回答，请如实说明「根据现有资料无法完整回答该问题」，并尽可能给出已知部分。
5. 若参考资料与问题完全无关，请回复「未找到与您问题相关的资料，建议咨询相关部门或查阅官方文件」。
6. 涉及时间、金额、流程等关键信息时务必准确引用，避免使用「大概」「可能」等模糊表述。

**来源汇总**：在回答的最末尾，统一列出所有引用的知识库来源，格式如下：

---
📚 **知识库来源**
- [来源1] 文件名，第X页（知识库：知识库名称）
- [来源2] 文件名，第X页（知识库：知识库名称）
---

请输出最终回答："""

